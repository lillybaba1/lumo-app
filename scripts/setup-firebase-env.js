#!/usr/bin/env node

/**
 * Firebase Environment Setup Script
 * Helps set up .env.local with Firebase credentials
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const ENV_FILE = path.join(process.cwd(), '.env.local');
const ENV_EXAMPLE = path.join(process.cwd(), '.env.example');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

function question(query) {
  return new Promise(resolve => rl.question(query, resolve));
}

async function main() {
  console.log('\n🔧 Firebase Environment Setup\n');
  console.log('This script will help you configure Firebase credentials for local development.\n');

  // Check if .env.local already exists
  if (fs.existsSync(ENV_FILE)) {
    console.log('⚠️  .env.local already exists!\n');
    const overwrite = await question('Do you want to overwrite it? (y/N): ');
    if (overwrite.toLowerCase() !== 'y') {
      console.log('Cancelled. Your existing .env.local was not modified.');
      rl.close();
      return;
    }
  }

  console.log('\n📋 You will need:\n');
  console.log('1. Firebase Service Account JSON');
  console.log('   Get from: https://console.firebase.google.com/');
  console.log('   → Select project: lumo-app-183f5');
  console.log('   → Settings → Service Accounts → Generate new private key\n');
  console.log('2. (Optional) Google AI API Key');
  console.log('   Get from: https://aistudio.google.com/app/apikey\n');

  const proceed = await question('Ready to proceed? (Y/n): ');
  if (proceed.toLowerCase() === 'n') {
    console.log('Cancelled.');
    rl.close();
    return;
  }

  // Template for .env.local
  let envContent = `# Local Environment Variables
# Generated by setup-firebase-env.js

# Firebase Client Config (Public - Safe to expose)
NEXT_PUBLIC_FIREBASE_API_KEY=AIzaSyBb2rTZAGNbKDcF6lBxxCubKlxmks1n0ng
NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=lumo-app-183f5.firebaseapp.com
NEXT_PUBLIC_FIREBASE_PROJECT_ID=lumo-app-183f5
NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=lumo-app-183f5.firebasestorage.app
NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=599053873389
NEXT_PUBLIC_FIREBASE_APP_ID=1:599053873389:web:7ae9fc52e26be1e3d89ce4
NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID=G-EHRCCLS6CV

`;

  console.log('\n1️⃣  Firebase Service Account JSON\n');
  console.log('Paste the entire JSON content from the downloaded service account file.');
  console.log('It should start with {"type":"service_account",...}\n');
  console.log('Paste here (press Enter on empty line when done):');

  let serviceAccountJson = '';
  let emptyLineCount = 0;

  // Read multiline input
  rl.on('line', (line) => {
    if (line.trim() === '') {
      emptyLineCount++;
      if (emptyLineCount >= 1 && serviceAccountJson.length > 0) {
        processServiceAccount();
      }
    } else {
      emptyLineCount = 0;
      serviceAccountJson += line;
    }
  });

  async function processServiceAccount() {
    rl.removeAllListeners('line');

    // Validate JSON
    try {
      const parsed = JSON.parse(serviceAccountJson);
      if (!parsed.project_id || !parsed.private_key || !parsed.client_email) {
        throw new Error('Invalid service account JSON structure');
      }

      console.log('\n✅ Valid service account JSON detected');
      console.log(`   Project ID: ${parsed.project_id}`);
      console.log(`   Client Email: ${parsed.client_email}\n`);

      // Add to env content (remove newlines from private key)
      const jsonOneLine = serviceAccountJson.replace(/\n/g, '');
      envContent += `# Firebase Admin (PRIVATE - Never commit this!)\n`;
      envContent += `FIREBASE_SERVICE_ACCOUNT_JSON=${jsonOneLine}\n`;
      envContent += `FIREBASE_STORAGE_BUCKET=lumo-app-183f5.firebasestorage.app\n\n`;

    } catch (err) {
      console.log('\n❌ Invalid JSON format!');
      console.log('   Error:', err.message);
      console.log('\nPlease check the JSON and try again.');
      rl.close();
      return;
    }

    // Session config
    envContent += `# Session Configuration\n`;
    envContent += `FIREBASE_COOKIE_NAME=session\n\n`;

    // Google AI API key (optional)
    console.log('2️⃣  Google AI API Key (Optional - for AI assistant)\n');
    const googleApiKey = await question('Paste your Google AI API key (or press Enter to skip): ');

    if (googleApiKey.trim()) {
      envContent += `# Google AI (for AI assistant)\n`;
      envContent += `GOOGLE_API_KEY=${googleApiKey.trim()}\n\n`;
    } else {
      envContent += `# Google AI (for AI assistant) - NOT SET\n`;
      envContent += `# GOOGLE_API_KEY=your_key_here\n\n`;
    }

    // Write .env.local file
    try {
      fs.writeFileSync(ENV_FILE, envContent, 'utf8');
      console.log('\n✅ Successfully created .env.local!\n');

      // Verification
      console.log('📋 Verification:\n');
      console.log('✓ FIREBASE_SERVICE_ACCOUNT_JSON is set');
      console.log('✓ FIREBASE_STORAGE_BUCKET is set');
      console.log('✓ All NEXT_PUBLIC_* variables are set');
      if (googleApiKey.trim()) {
        console.log('✓ GOOGLE_API_KEY is set');
      } else {
        console.log('⚠ GOOGLE_API_KEY is not set (AI assistant will not work)');
      }

      console.log('\n📝 Next steps:\n');
      console.log('1. Configure Firebase Storage CORS:');
      console.log('   See FIREBASE_IMAGE_FIX.md Step 3\n');
      console.log('2. Update Firebase Storage rules:');
      console.log('   See FIREBASE_IMAGE_FIX.md Step 4\n');
      console.log('3. Restart your dev server:');
      console.log('   npm run dev\n');
      console.log('4. Test image upload:');
      console.log('   Visit /admin/products/add\n');

    } catch (err) {
      console.error('\n❌ Failed to write .env.local:', err.message);
    }

    rl.close();
  }
}

main().catch(err => {
  console.error('Error:', err);
  rl.close();
  process.exit(1);
});
